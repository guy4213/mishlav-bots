"""Prompt, knowledge base and per-call variables — read from the repo's config/, same files as provider A."""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

import yaml

TZ = ZoneInfo("Asia/Jerusalem")

HE_WEEKDAYS = ["יום שני", "יום שלישי", "יום רביעי", "יום חמישי", "יום שישי", "שבת", "יום ראשון"]  # Mon=0
HE_MONTHS = ["ינואר", "פברואר", "מרץ", "אפריל", "מאי", "יוני", "יולי", "אוגוסט", "ספטמבר", "אוקטובר", "נובמבר", "דצמבר"]


def find_repo_root(start: Path | None = None) -> Path:
    """MISHLAV_ROOT, else the nearest parent holding config/settings.yaml (same rule as the TS side)."""
    if env := os.environ.get("MISHLAV_ROOT"):
        return Path(env).resolve()
    here = (start or Path(__file__)).resolve()
    for p in [here, *here.parents]:
        if (p / "config" / "settings.yaml").is_file():
            return p
    raise RuntimeError("repo root not found (no config/settings.yaml above this file); set MISHLAV_ROOT")


@dataclass(frozen=True)
class CallVars:
    first_name: str
    bot_name: str
    interested_day_id: str = ""
    current_datetime: str = ""


def format_now_he(now: datetime) -> str:
    """e.g. 'יום שלישי, 8 בדצמבר 2026, 10:05' — Israel time."""
    local = now.astimezone(TZ)
    return f"{HE_WEEKDAYS[local.weekday()]}, {local.day} ב{HE_MONTHS[local.month - 1]} {local.year}, {local:%H:%M}"


_VAR = re.compile(r"\{\{\s*([a-z_]+)\s*\}\}")


def render(template: str, values: dict[str, str]) -> str:
    """Substitute {{var}}; unknown variables are an error (a typo would otherwise reach the caller)."""

    def sub(m: re.Match[str]) -> str:
        name = m.group(1)
        if name not in values:
            raise KeyError(f"prompt variable {{{{{name}}}}} has no value")
        return values[name]

    return _VAR.sub(sub, template)


def _split_front_matter(text: str) -> tuple[dict[str, Any], str]:
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    return yaml.safe_load(m.group(1)) or {}, m.group(2)


def knowledge_appendix(root: Path) -> str:
    """general.md + every day file, as one Hebrew block appended to the prompt (spec: B/C append knowledge)."""
    kdir = root / "config" / "knowledge"
    parts = ["# מאגר ידע (מקור המידע היחיד – לא לענות על דבר שלא מופיע כאן או בכלי get_day_info)"]
    general = kdir / "general.md"
    if general.is_file():
        parts.append(general.read_text(encoding="utf-8").strip())
    for f in sorted((kdir / "days").glob("*.md")):
        meta, body = _split_front_matter(f.read_text(encoding="utf-8"))
        facts = ", ".join(
            f"{k}: {meta[k]}"
            for k in ("id", "date", "start", "end", "format", "location", "price_ils", "open_for_registration")
            if k in meta
        )
        parts.append(f"## day_id `{meta.get('id', f.stem)}`\n{facts}\n\n{body.strip()}")
    return "\n\n".join(parts)


def build_instructions(root: Path, call: CallVars) -> str:
    prompt = (root / "config" / "prompt.md").read_text(encoding="utf-8")
    values = {
        "first_name": call.first_name,
        "bot_name": call.bot_name,
        "interested_day_id": call.interested_day_id or "לא ידוע",
        "current_datetime": call.current_datetime,
    }
    return render(prompt, values) + "\n\n" + knowledge_appendix(root)


def scenario_context(root: Path, scenario_id: str | None) -> dict[str, str]:
    """The `context:` block of a test scenario (first_name, interested_day_id). Empty if not found."""
    if not scenario_id:
        return {}
    for f in sorted((root / "tests" / "scenarios").rglob("*.y*ml")):
        data = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        if data.get("id") == scenario_id:
            return {k: str(v) for k, v in (data.get("context") or {}).items()}
    return {}


def load_tool_definitions(root: Path) -> list[dict[str, Any]]:
    """config/tools.json (generated by `npm run tools:export`) — the single source of the tool schemas."""
    data = json.loads((root / "config" / "tools.json").read_text(encoding="utf-8"))
    return data["tools"]
