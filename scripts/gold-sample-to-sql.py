"""Turn a Gold student export (.xlsx) into INSERTs for the Supabase `contacts` table, using the column mapping in
config/settings.yaml (gold_import). Used for supabase/seed.sql from apps/backend/fixtures/gold-sample.xlsx until the
real Importer (Phase 4) exists. Fails if the file has a column the mapping doesn't know.

Run: uv run --with openpyxl --with pyyaml python scripts/gold-sample-to-sql.py [file.xlsx] > supabase/seed.sql
"""
import re
import sys
from pathlib import Path

import yaml
from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parents[1]


def e164(phone: str | None) -> str | None:
    """Israeli number as dialed: 053-4271418 / 053 4271418 / 0534271418 -> +972534271418."""
    digits = re.sub(r"\D", "", phone or "")
    if digits.startswith("972"):
        digits = digits[3:]
    digits = digits.lstrip("0")
    return f"+972{digits}" if 8 <= len(digits) <= 9 else None


def sql(v) -> str:
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "apps" / "backend" / "fixtures" / "gold-sample.xlsx"
    gi = yaml.safe_load((ROOT / "config" / "settings.yaml").read_text(encoding="utf-8"))["gold_import"]
    mapping: dict[str, str] = gi["columns"]
    ws = load_workbook(src, read_only=True)[gi.get("sheet")] if gi.get("sheet") else load_workbook(src).active
    rows = list(ws.iter_rows(values_only=True))
    headers = ["" if h is None else str(h).strip() for h in rows[0]]
    unknown = [h for h in headers if h not in mapping]
    if unknown:
        sys.exit(f"columns not in gold_import.columns: {unknown}")
    cols = [mapping[h] for h in headers] + ["first_name", "phone_e164"]
    out = [f"-- generated by scripts/gold-sample-to-sql.py from {src.relative_to(ROOT)}", f"insert into contacts ({', '.join(cols)}) values"]
    values = []
    for row in rows[1:]:
        rec = {}
        for h, v in zip(headers, row):
            v = str(v).strip() if v is not None else None
            rec[mapping[h]] = None if v in ("", "Empty") else v
        rec["first_name"] = (rec.get("full_name") or "").split(" ")[0] or None
        rec["phone_e164"] = e164(rec.get("phone"))
        values.append("  (" + ", ".join(sql(rec[c]) for c in cols) + ")")
    out.append(",\n".join(values))
    out.append("on conflict (gold_record_id) do nothing;")
    print("\n".join(out))


if __name__ == "__main__":
    main()
